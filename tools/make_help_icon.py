"""Help page icon atlas (128x128 DXT5, white glyph on transparent, same style as the base game help icons).
Run from the mod folder: python tools/make_help_icon.py
Writes help/vtszHelpIcons.dds, help/vtszHelpIcons.xml, assets/vtszHelpIcons.png (preview)."""
import math
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = 8  # supersampling
SIZE = 128 * S
W = (255, 255, 255, 255)


def grain(d, cx, cy, angle, length, width):
    """One ellipse-shaped grain centred at cx,cy, rotated by angle (degrees, 0 = pointing up)."""
    pts = []
    for i in range(24):
        t = 2 * math.pi * i / 24
        x, y = math.cos(t) * width / 2, math.sin(t) * length / 2
        a = math.radians(angle)
        pts.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
    d.polygon(pts, fill=W)


def wheat():
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    cx = SIZE / 2
    top, bottom = 10 * S, 120 * S
    d.line((cx, 36 * S, cx, bottom), fill=W, width=int(5 * S))
    grain(d, cx, 14 * S, 0, 22 * S, 11 * S)
    for i in range(5):
        y = (30 + i * 15) * S
        off = (14 + i * 0.4) * S
        grain(d, cx - off, y, -30, 22 * S, 10 * S)
        grain(d, cx + off, y, 30, 22 * S, 10 * S)
    # two leaves at the stem
    for sign in (-1, 1):
        d.polygon([(cx, 112 * S), (cx + sign * 34 * S, 96 * S), (cx + sign * 26 * S, 106 * S), (cx, 118 * S)], fill=W)
    return img.resize((128, 128), Image.LANCZOS)


def main():
    os.makedirs(os.path.join(ROOT, "help"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
    icon = wheat()
    icon.save(os.path.join(ROOT, "help", "vtszHelpIcons.dds"), format="DDS", pixel_format="DXT5")
    bg = Image.new("RGBA", icon.size, (60, 60, 60, 255))
    bg.alpha_composite(icon)
    bg.convert("RGB").resize((256, 256)).save(os.path.join(ROOT, "assets", "vtszHelpIcons.png"))
    with open(os.path.join(ROOT, "help", "vtszHelpIcons.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write('''<?xml version="1.0" encoding="utf-8" standalone="no" ?>
<!-- Page icon of the in-game help. Generated by tools/make_help_icon.py. -->
<texture>
  <meta>
    <filename>vtszHelpIcons.png</filename>
    <size width="128" height="128"/>
  </meta>
  <slices>
    <slice id="cropReq" uvs="0px 0px 128px 128px"/>
  </slices>
</texture>
''')
    print("help icon written")


if __name__ == "__main__":
    main()
